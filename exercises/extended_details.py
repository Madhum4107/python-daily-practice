"""Input/output exercise with a third field."""

def main():
    name = input("Name: ").strip()
    age = input("Age: ").strip()
    address = input("Address: ").strip()
    print(f"My name is {name}.")
    print(f"My age is {age}.")
    print(f"My address is {address}.")

if __name__ == "__main__":
    main()
